"""Document generation endpoint — study notes, cheat sheets, PYQ-style content.

Supports JSON (for frontend rendering) and PDF (for download).
"""

from __future__ import annotations

import io
from datetime import datetime

from fastapi import APIRouter, Query
from fastapi.responses import StreamingResponse
from pydantic import BaseModel

from app.services.generation_v2 import generate_grounded_answer
from app.services.retrieval_v2 import retrieve_sources
from app.services.credon_brain import credon_answer
from app.services.doc_generator import (
    generate_notes_pdf,
    generate_cheat_sheet_pdf,
    generate_pyq_pdf,
)
from app.services.chat_store import get_transcript, list_sessions

router = APIRouter()


class AnswerPdfRequest(BaseModel):
    title: str
    content: str
    subject: str = ""
    user_id: str = "anonymous"


class ChatPdfRequest(BaseModel):
    user_id: str
    session_id: str


class AllChatsPdfRequest(BaseModel):
    user_id: str


@router.get("/generate/notes")
async def generate_notes(
    topic: str = Query(..., description="Topic to generate notes for"),
    user_id: str = Query("anonymous"),
    detail: str = Query("medium", description="brief | medium | detailed"),
    format: str = Query("json", description="json | text"),
):
    """Generate study notes for a topic."""
    detail_instruction = {
        "brief": "Create concise bullet-point notes (1-2 pages max).",
        "medium": "Create comprehensive study notes with explanations (3-5 pages).",
        "detailed": "Create extremely detailed notes with examples, diagrams descriptions, and practice questions (5-10 pages).",
    }.get(detail, "Create comprehensive study notes.")

    prompt = (
        f"Generate detailed study notes on: {topic}\n\n"
        f"Instructions: {detail_instruction}\n"
        f"Structure the notes with:\n"
        f"1. Key Concepts & Definitions\n"
        f"2. Important Points\n"
        f"3. Examples & Explanations\n"
        f"4. Common Mistakes to Avoid\n"
        f"5. Quick Revision Summary\n"
        f"6. Practice Questions (3-5)\n\n"
        f"Use clear formatting with headers, bullet points, and bold key terms."
    )

    sources = retrieve_sources(topic, max_results=5)
    brain_answer = credon_answer(topic, sources=None, target_language="en")

    notes = generate_grounded_answer(
        prompt, sources, "en", model=None, thinking="",
    )

    if not notes or len(notes) < 100:
        notes = brain_answer or f"# Study Notes: {topic}\n\nContent generation is currently limited. Please try again."

    header = (
        f"# \U0001f4da Study Notes: {topic}\n"
        f"*Generated by Credon AI on {datetime.now().strftime('%B %d, %Y at %I:%M %p')}*\n\n"
        f"---\n\n"
    )

    content = header + notes

    if format == "text":
        return StreamingResponse(
            io.BytesIO(content.encode("utf-8")),
            media_type="text/plain",
            headers={
                "Content-Disposition": f'attachment; filename="notes-{topic[:30].replace(" ", "-")}.txt"'
            },
        )

    return {"ok": True, "content": content, "topic": topic, "format": "markdown"}


